/*==================================================================
    Cardinal 5-Port Mesh Router Node Module
    - Instantiates 5 Input Controllers and 5 Output Controllers
    - Coordinates: (MY_X, MY_Y)
    - Fully wires crossbar data, request, and grant buses
====================================================================
Signal meaning:
u/d/r/l/pe – Up, Down, Right, Left
cw – clockwise direction
ccw – counter-clockwise direction
i/o – input/output
pe – processing element
s/r/d – send, ready, data
polarity – even/odd clk cycle
==================================================================*/

module router_node #(
    parameter [1:0] MY_X = 2'd0,
    parameter [1:0] MY_Y = 2'd0
)(
    input wire clk,
    input wire reset,
    output reg polarity,

    // Processing Element (PE) Local Port
    input wire pesi,            // PE send in
    output wire peri,           // PE ready in
    input wire [63:0] pedi,     // PE data in
    output wire [63:0] pedo,    // PE data out
    input wire pero,            // PE ready out
    output wire peso,           // PE send out

    // North Network Port
    input wire up_si,            // North send in
    output wire up_ri,           // North ready in
    input wire [63:0] up_di,     // North data in
    output wire [63:0] up_do,    // North data out
    input wire up_ro,            // North ready out
    output wire up_so,           // North send out

    // South Network Port
    input wire down_si,            // South send in
    output wire down_ri,           // South ready in
    input wire [63:0] down_di,     // South data in
    output wire [63:0] down_do,    // South data out
    input wire down_ro,            // South ready out
    output wire down_so,           // South send out

    // East Network Port
    input wire right_si,             // East send in
    output wire right_ri,            // East ready in
    input wire [63:0] right_di,      // East data in
    output wire [63:0] right_do,     // East data out
    input wire right_ro,             // East ready out
    output wire right_so,            // East send out

    // West Network Port
    input wire left_si,             // West send in
    output wire left_ri,            // West ready in
    input wire [63:0] left_di,      // West data in
    output wire [63:0] left_do,     // West data out
    input wire left_ro,             // West ready out
    output wire left_so             // West send out
);

// ================================
// Polarity Generator
// ================================
// polarity is 0 during reset and toggles every rising edge thereafter
always @(posedge clk) begin
    if (reset) begin
        polarity <= 1'b0;
    end
    else begin
        polarity <= ~polarity;
    end
end

// ================================
// Internal Crossbar Wires
// ================================
// Data buses out of input controllers
wire [63:0] data_pe_internal;
wire [63:0] data_up_internal;
wire [63:0] data_down_internal;
wire [63:0] data_right_internal;
wire [63:0] data_left_internal;

// Requests generated by input controllers
wire req_pe2u, req_pe2d, req_pe2r, req_pe2l, req_pe2pe;
wire req_u2u, req_u2d, req_u2r, req_u2l, req_u2pe;
wire req_d2u, req_d2d, req_d2r, req_d2l, req_d2pe;
wire req_r2u, req_r2d, req_r2r, req_r2l, req_r2pe;
wire req_l2u, req_l2d, req_l2r, req_l2l, req_l2pe;

// Grants generated by output controllers
wire grant_pe2pe, grant_pe2u, grant_pe2d, grant_pe2r, grant_pe2l;
wire grant_u2pe, grant_u2u, grant_u2d, grant_u2r, grant_u2l;
wire grant_d2pe, grant_d2u, grant_d2d, grant_d2r, grant_d2l;
wire grant_r2pe, grant_r2u, grant_r2d, grant_r2r, grant_r2l;
wire grant_l2pe, grant_l2u, grant_l2d, grant_l2r, grant_l2l;

// Aggregated Grants fed back to each Input Controller
wire grant_to_pe = grant_pe2pe | grant_u2pe | grant_d2pe | grant_r2pe | grant_l2pe;
wire grant_to_up = grant_pe2u | grant_d2u | grant_r2u | grant_l2u;
wire grant_to_down = grant_pe2d | grant_u2d | grant_r2d | grant_l2d;
wire grant_to_right = grant_pe2r | grant_u2r | grant_d2r | grant_l2r;
wire grant_to_left = grant_pe2l | grant_u2l | grant_d2l | grant_r2l;

// ================================
// 5 Input Controllers
// ================================
router_input_ctrl #(.MY_X(MY_X), .MY_Y(MY_Y)) u_in_pe (
    .clk              (clk),
    .reset            (reset),
    .polarity         (polarity),

    // External channel interface
    .data_in          (pedi),
    .send_in          (pesi),
    .ready_in         (peri),

    // Internal channel interface
    .grant_in         (grant_to_pe),
    .selected_data_out(data_pe_internal),
    .request_up       (req_pe2u),
    .request_down     (req_pe2d),
    .request_right    (req_pe2r),
    .request_left     (req_pe2l),
    .request_pe       (req_pe2pe)
);

router_input_ctrl #(.MY_X(MY_X), .MY_Y(MY_Y)) u_in_up (
    .clk              (clk),
    .reset            (reset),
    .polarity         (polarity),

    // External channel interface
    .data_in          (up_di),
    .send_in          (up_si),
    .ready_in         (up_ri),

    // Internal channel interface
    .grant_in         (grant_to_up),
    .selected_data_out(data_up_internal),
    .request_up       (req_u2u),
    .request_down     (req_u2d),
    .request_right    (req_u2r),
    .request_left     (req_u2l),
    .request_pe       (req_u2pe)
);

router_input_ctrl #(.MY_X(MY_X), .MY_Y(MY_Y)) u_in_down (
    .clk              (clk),
    .reset            (reset),
    .polarity         (polarity),

    // External channel interface
    .data_in          (down_di),
    .send_in          (down_si),
    .ready_in         (down_ri),

    // Internal channel interface
    .grant_in         (grant_to_down),
    .selected_data_out(data_down_internal),
    .request_up       (req_d2u),
    .request_down     (req_d2d),
    .request_right    (req_d2r),
    .request_left     (req_d2l),
    .request_pe       (req_d2pe)
);

router_input_ctrl #(.MY_X(MY_X), .MY_Y(MY_Y)) u_in_right (
    .clk              (clk),
    .reset            (reset),
    .polarity         (polarity),

    // External channel interface
    .data_in          (right_di),
    .send_in          (right_si),
    .ready_in         (right_ri),

    // Internal channel interface
    .grant_in         (grant_to_right),
    .selected_data_out(data_right_internal),
    .request_up       (req_r2u),
    .request_down     (req_r2d),
    .request_right    (req_r2r),
    .request_left     (req_r2l),
    .request_pe       (req_r2pe)
);

router_input_ctrl #(.MY_X(MY_X), .MY_Y(MY_Y)) u_in_left (
    .clk              (clk),
    .reset            (reset),
    .polarity         (polarity),

    // External channel interface
    .data_in          (left_di),
    .send_in          (left_si),
    .ready_in         (left_ri),

    // Internal channel interface
    .grant_in         (grant_to_left),
    .selected_data_out(data_left_internal),
    .request_up       (req_l2u),
    .request_down     (req_l2d),
    .request_right    (req_l2r),
    .request_left     (req_l2l),
    .request_pe       (req_l2pe)
);

// ================================
// 5 Output Controllers
// ================================
// PE Output: candidate inputs = up, down, right, left (no self-delivery)
router_output_ctrl u_out_pe (
    .clk              (clk),
    .reset            (reset),
    .polarity         (polarity),

    // Internal crossbar data from candidate input controllers
    .data_in_pe       (64'h0),
    .data_in_up       (data_up_internal),
    .data_in_down     (data_down_internal),
    .data_in_right    (data_right_internal),
    .data_in_left     (data_left_internal),

    // Requests from candidate input controllers
    .req_in_pe        (1'b0),
    .req_in_up        (req_u2pe),
    .req_in_down      (req_d2pe),
    .req_in_right     (req_r2pe),
    .req_in_left      (req_l2pe),

    // Grants back to candidate input controllers
    .grant_out_pe     (grant_pe2pe),
    .grant_out_up     (grant_pe2u),
    .grant_out_down   (grant_pe2d),
    .grant_out_right  (grant_pe2r),
    .grant_out_left   (grant_pe2l),

    // External link interface
    .data_out         (pedo),
    .send_out         (peso),
    .ready_in         (pero)
);

// Up Output: candidate inputs = pe, down, right, left (never reverses to up)
router_output_ctrl u_out_up (
    .clk              (clk),
    .reset            (reset),
    .polarity         (polarity),

    // Internal crossbar data from candidate input controllers
    .data_in_pe       (data_pe_internal),
    .data_in_up       (64'h0),
    .data_in_down     (data_down_internal),
    .data_in_right    (data_right_internal),
    .data_in_left     (data_left_internal),

    // Requests from candidate input controllers
    .req_in_pe        (req_pe2u),
    .req_in_up        (1'b0),
    .req_in_down      (req_d2u),
    .req_in_right     (req_r2u),
    .req_in_left      (req_l2u),

    // Grants back to candidate input controllers
    .grant_out_pe     (grant_u2pe),
    .grant_out_up     (grant_u2u),
    .grant_out_down   (grant_u2d),
    .grant_out_right  (grant_u2r),
    .grant_out_left   (grant_u2l),

    // External link interface
    .data_out         (up_do), 
    .send_out         (up_so),
    .ready_in         (up_ro)
);

// Down Output: candidate inputs = pe, up, right, left (never reverses to down)
router_output_ctrl u_out_down (
    .clk              (clk),
    .reset            (reset),
    .polarity         (polarity),

    // Internal crossbar data from candidate input controllers
    .data_in_pe       (data_pe_internal),
    .data_in_up       (data_up_internal),
    .data_in_down     (64'h0),
    .data_in_right    (data_right_internal),
    .data_in_left     (data_left_internal),

    // Requests from candidate input controllers
    .req_in_pe        (req_pe2d),
    .req_in_up        (req_u2d),
    .req_in_down      (1'b0),
    .req_in_right     (req_r2d),
    .req_in_left      (req_l2d),

    // Grants back to candidate input controllers
    .grant_out_pe     (grant_d2pe),
    .grant_out_up     (grant_d2u),
    .grant_out_down   (grant_d2d),
    .grant_out_right  (grant_d2r),
    .grant_out_left   (grant_d2l),

    // External link interface
    .data_out         (down_do),
    .send_out         (down_so),
    .ready_in         (down_ro)
);

// Left Output: X-Y routing allows only pe and right (no Y-to-X turns)
router_output_ctrl u_out_right (
    .clk              (clk),
    .reset            (reset),
    .polarity         (polarity),

    // Internal crossbar data from candidate input controllers
    .data_in_pe       (data_pe_internal),
    .data_in_up       (64'h0),
    .data_in_down     (64'h0),
    .data_in_right    (64'h0),
    .data_in_left     (data_left_internal),

    // Requests from candidate input controllers
    .req_in_pe        (req_pe2r),
    .req_in_up        (1'b0),
    .req_in_down      (1'b0),
    .req_in_right     (1'b0),
    .req_in_left      (req_l2r),

    // Grants back to candidate input controllers
    .grant_out_pe     (grant_r2pe),
    .grant_out_up     (grant_r2u),
    .grant_out_down   (grant_r2d),
    .grant_out_right  (grant_r2r),
    .grant_out_left   (grant_r2l),

    // External link interface
    .data_out         (right_do),
    .send_out         (right_so),
    .ready_in         (right_ro)
);

// Left Output: X-Y routing allows only pe and right (no Y-to-X turns)
router_output_ctrl u_out_left (
    .clk              (clk),
    .reset            (reset),
    .polarity         (polarity),

    // Internal crossbar data from candidate input controllers
    .data_in_pe       (data_pe_internal),
    .data_in_up       (64'h0),
    .data_in_down     (64'h0),
    .data_in_right    (data_right_internal),
    .data_in_left     (64'h0),

    // Requests from candidate input controllers
    .req_in_pe        (req_pe2l),
    .req_in_up        (1'b0),
    .req_in_down      (1'b0),
    .req_in_right     (req_r2l),
    .req_in_left      (1'b0),

    // Grants back to candidate input controllers
    .grant_out_pe     (grant_l2pe),
    .grant_out_up     (grant_l2u),
    .grant_out_down   (grant_l2d),
    .grant_out_right  (grant_l2r),
    .grant_out_left   (grant_l2l),

    // External link interface
    .data_out         (left_do),
    .send_out         (left_so),
    .ready_in         (left_ro)
);

endmodule
